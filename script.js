const root = document.documentElement;
const pageLanguage = root.dataset.pageLanguage === 'ar' ? 'ar' : 'en';
const languageStatus = document.querySelector('#language-status');
const menuToggle = document.querySelector('[data-menu-toggle]');
const nav = document.querySelector('.nav');
const copyFeedback = document.querySelector('[data-copy-feedback]');
const meta = {
  description: document.querySelector('meta[name="description"]'),
  language: document.querySelector('meta[name="language"]'),
  ogTitle: document.querySelector('meta[property="og:title"]'),
  ogDescription: document.querySelector('meta[property="og:description"]'),
  ogLocale: document.querySelector('meta[property="og:locale"]'),
  ogUrl: document.querySelector('meta[property="og:url"]'),
  twitterTitle: document.querySelector('meta[name="twitter:title"]'),
  twitterDescription: document.querySelector('meta[name="twitter:description"]'),
  canonical: document.querySelector('link[rel="canonical"]')
};

let activeLanguage = root.lang === 'ar' ? 'ar' : pageLanguage;
let menuScrollY = 0;
let pendingMenuAction = null;
let menuHistoryBackPending = false;
let previousScrollRestoration = null;

function getTranslation(language, key) {
  return key.split('.').reduce((value, segment) => value && value[segment], translations[language]);
}

function setMetaContent(element, value) {
  if (element && value) element.setAttribute('content', value);
}

function languageUrl(language) {
  return language === 'ar' ? 'https://tolvano.com/ar/' : 'https://tolvano.com/';
}

function menuIsOpen() {
  return Boolean(document.body && document.body.classList.contains('menu-open'));
}

function currentHistoryState() {
  const state = window.history && window.history.state;
  return state && typeof state === 'object' ? state : {};
}

function menuHistoryIsCurrent() {
  return currentHistoryState().tolvanoMenuOpen === true;
}

function updateMenuToggleLabel() {
  if (!menuToggle) return;
  const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
  const labelKey = isOpen ? 'meta.menuClose' : 'meta.menuOpen';
  menuToggle.setAttribute('aria-label', getTranslation(activeLanguage, labelKey));
}

function setMenuVisualState(isOpen) {
  if (!menuToggle || !nav) return;

  const wasOpen = menuIsOpen();
  if (isOpen === wasOpen) return;

  if (isOpen) {
    menuScrollY = window.scrollY;
    document.body.style.setProperty('--menu-scroll-offset', `-${menuScrollY}px`);
    if (typeof window.history.scrollRestoration === 'string') {
      previousScrollRestoration = window.history.scrollRestoration;
      window.history.scrollRestoration = 'manual';
    }
  }

  menuToggle.classList.toggle('open', isOpen);
  nav.classList.toggle('mobile-open', isOpen);
  root.classList.toggle('menu-open', isOpen);
  document.body.classList.toggle('menu-open', isOpen);
  menuToggle.setAttribute('aria-expanded', String(isOpen));
  updateMenuToggleLabel();

  if (!isOpen) {
    document.body.style.removeProperty('--menu-scroll-offset');
    const previousScrollBehavior = root.style.scrollBehavior;
    root.style.scrollBehavior = 'auto';
    window.scrollTo(0, menuScrollY);
    root.style.scrollBehavior = previousScrollBehavior;
  }
}

function restoreHistoryScrollRestoration() {
  if (previousScrollRestoration === null) return;

  const restore = () => {
    window.history.scrollRestoration = previousScrollRestoration;
    previousScrollRestoration = null;
  };

  if (typeof window.requestAnimationFrame === 'function') {
    window.requestAnimationFrame(restore);
  } else {
    restore();
  }
}

function pushMenuHistoryState() {
  try {
    window.history.pushState(
      { ...currentHistoryState(), tolvanoMenuOpen: true },
      '',
      window.location.href
    );
    return true;
  } catch (error) {
    return false;
  }
}

function runPendingMenuAction() {
  const action = pendingMenuAction;
  pendingMenuAction = null;
  if (!action) return;

  if (typeof window.requestAnimationFrame === 'function') {
    window.requestAnimationFrame(action);
  } else {
    action();
  }
}

function openMenu() {
  if (menuHistoryBackPending || menuIsOpen()) return;

  if (menuHistoryIsCurrent()) {
    setMenuVisualState(true);
    return;
  }

  setMenuVisualState(true);
  pushMenuHistoryState();
}

function closeMenu(afterClose = null) {
  if (afterClose) pendingMenuAction = afterClose;
  if (menuHistoryBackPending) return;

  if (menuHistoryIsCurrent()) {
    menuHistoryBackPending = true;
    setMenuVisualState(false);
    try {
      window.history.back();
      return;
    } catch (error) {
      menuHistoryBackPending = false;
    }
  }

  setMenuVisualState(false);
  restoreHistoryScrollRestoration();
  runPendingMenuAction();
}

function setMenuState(isOpen, { afterClose = null } = {}) {
  if (isOpen) {
    openMenu();
  } else {
    closeMenu(afterClose);
  }
}

function updateBrowserUrl(language) {
  try {
    const url = new URL(window.location.href);
    const projectRoot = url.pathname.startsWith('/TOLVANO/') ? '/TOLVANO/' : '/';
    const pathname = language === 'ar' ? `${projectRoot}ar/` : projectRoot;
    const state = currentHistoryState();
    delete state.tolvanoMenuOpen;
    window.history.replaceState({ ...state, language }, '', `${pathname}${url.hash}`);
  } catch (error) {
    // The visual language switch remains available when history APIs are unavailable.
  }
}

function applyLanguage(language, { announce = false, updateUrl = false } = {}) {
  if (!translations[language]) return;

  activeLanguage = language;
  root.lang = language;
  root.dir = language === 'ar' ? 'rtl' : 'ltr';
  root.dataset.language = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = getTranslation(language, element.dataset.i18n);
    if (value) element.textContent = value;
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = getTranslation(language, element.dataset.i18nHtml);
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = getTranslation(language, element.dataset.i18nAriaLabel);
    if (value) element.setAttribute('aria-label', value);
  });

  document.querySelectorAll('[data-i18n-mailto]').forEach((element) => {
    const subject = getTranslation(language, element.dataset.i18nMailto);
    const email = element.dataset.mailtoEmail;
    if (subject && email) element.href = `mailto:${email}?subject=${encodeURIComponent(subject)}`;
  });

  document.querySelectorAll('[data-language-option]').forEach((link) => {
    if (link.dataset.languageOption === language) {
      link.setAttribute('aria-current', 'page');
    } else {
      link.removeAttribute('aria-current');
    }
  });

  document.title = getTranslation(language, 'meta.title');
  setMetaContent(meta.description, getTranslation(language, 'meta.description'));
  setMetaContent(meta.language, getTranslation(language, 'meta.language'));
  setMetaContent(meta.ogTitle, getTranslation(language, 'meta.ogTitle'));
  setMetaContent(meta.ogDescription, getTranslation(language, 'meta.ogDescription'));
  setMetaContent(meta.ogLocale, getTranslation(language, 'meta.locale'));
  setMetaContent(meta.ogUrl, languageUrl(language));
  setMetaContent(meta.twitterTitle, getTranslation(language, 'meta.ogTitle'));
  setMetaContent(meta.twitterDescription, getTranslation(language, 'meta.ogDescription'));
  if (meta.canonical) meta.canonical.setAttribute('href', languageUrl(language));
  updateMenuToggleLabel();

  try {
    window.localStorage.setItem('tolvano-language', language);
  } catch (error) {
    // Storage is an enhancement; the switch still works in restricted contexts.
  }

  if (updateUrl) updateBrowserUrl(language);
  if (announce && languageStatus) languageStatus.textContent = getTranslation(language, 'meta.status');
}

document.querySelectorAll('[data-language-option]').forEach((link) => {
  link.addEventListener('click', (event) => {
    event.preventDefault();
    const applySelectedLanguage = () => {
      applyLanguage(link.dataset.languageOption, { announce: true, updateUrl: true });
    };

    if (menuIsOpen() || menuHistoryIsCurrent()) {
      setMenuState(false, { afterClose: applySelectedLanguage });
    } else {
      applySelectedLanguage();
    }
  });
});

if (menuToggle && nav) {
  menuToggle.addEventListener('click', () => {
    setMenuState(!menuIsOpen());
  });

  nav.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', (event) => {
      if (!menuIsOpen() && !menuHistoryIsCurrent()) return;

      event.preventDefault();
      const destination = link.getAttribute('href');
      setMenuState(false, {
        afterClose: () => {
          if (destination) window.location.href = destination;
        }
      });
    });
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && menuIsOpen()) {
      setMenuState(false);
    }
  });

  window.addEventListener('popstate', (event) => {
    menuHistoryBackPending = false;

    if (event.state && event.state.tolvanoMenuOpen === true) {
      setMenuVisualState(true);
      return;
    }

    setMenuVisualState(false);
    restoreHistoryScrollRestoration();
    runPendingMenuAction();
  });
}

function selectEmailAddress() {
  const email = document.querySelector('[data-email-address]');
  if (!email || !window.getSelection || !document.createRange) return;
  const range = document.createRange();
  range.selectNodeContents(email);
  const selection = window.getSelection();
  selection.removeAllRanges();
  selection.addRange(range);
}

async function copyEmailAddress(email) {
  try {
    if (typeof navigator !== 'undefined' && navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(email);
      return true;
    }
  } catch (error) {
    // A selectable address below is the explicit fallback.
  }
  selectEmailAddress();
  return false;
}

document.querySelectorAll('[data-copy-email]').forEach((button) => {
  button.addEventListener('click', async () => {
    const copied = await copyEmailAddress(button.dataset.copyEmail);
    if (copyFeedback) {
      copyFeedback.textContent = getTranslation(activeLanguage, copied ? 'contact.copySuccess' : 'contact.copyFallback');
    }
  });
});

